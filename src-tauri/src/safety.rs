//! Phase 0.6 reference guards. Not a complete filesystem or approval service.
use std::path::{Component, Path, PathBuf};

#[derive(Debug, PartialEq)]
pub enum PathError {
    Denied,
    ScopeUnavailable,
    Missing,
    AccessDenied,
    CheckFailed,
}

/// Existing targets only. Call immediately before use, never accept a UI-normalized path.
/// Canonicalization does not protect against a later reparse-point swap (see checklist).
pub fn existing_scoped_path(scope: &Path, path: &Path) -> Result<PathBuf, PathError> {
    if !path.is_absolute()
        || path.components().any(|c| matches!(c, Component::ParentDir))
        || !path.starts_with(scope)
    {
        return Err(PathError::Denied);
    }
    #[cfg(windows)]
    {
        let text = path.to_string_lossy();
        // Reject UNC/device namespaces and NTFS alternate data streams in UI input.
        if text.starts_with(r"\\")
            || text.starts_with("//")
            || text.chars().skip(2).any(|c| c == ':')
        {
            return Err(PathError::Denied);
        }
    }
    let canonical_scope = scope
        .canonicalize()
        .map_err(|_| PathError::ScopeUnavailable)?;
    let canonical_path = path.canonicalize().map_err(|e| match e.kind() {
        std::io::ErrorKind::NotFound => PathError::Missing,
        std::io::ErrorKind::PermissionDenied => PathError::AccessDenied,
        _ => PathError::CheckFailed,
    })?;
    if !canonical_path.starts_with(canonical_scope) {
        return Err(PathError::Denied);
    }
    Ok(canonical_path)
}

#[derive(Clone, Copy, PartialEq)]
pub enum OperationKind {
    Command,
    FileChange,
    Unknown,
}

/// Reference for a backend-owned, expiring, single-use pending approval.
/// The caller must derive fingerprint from the complete immutable operation.
pub struct PendingApproval {
    pub task_id: String,
    pub operation_fingerprint: String,
    pub window_label: String,
    pub kind: OperationKind,
    pub expires_at: u64,
    consumed: bool,
}
impl PendingApproval {
    pub fn new(
        task_id: String,
        operation_fingerprint: String,
        kind: OperationKind,
        expires_at: u64,
    ) -> Self {
        Self {
            task_id,
            operation_fingerprint,
            kind,
            expires_at,
            window_label: "main".into(),
            consumed: false,
        }
    }
    pub fn decide(
        &mut self,
        task: &str,
        fingerprint: &str,
        window: &str,
        now: u64,
        approve: bool,
    ) -> bool {
        if self.consumed
            || now >= self.expires_at
            || task != self.task_id
            || fingerprint != self.operation_fingerprint
            || window != self.window_label
        {
            return false;
        }
        self.consumed = true;
        approve && self.kind != OperationKind::Unknown
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    #[test]
    fn traversal_prefix_and_missing_paths_are_denied() {
        let root = std::env::temp_dir().join(super::super::ipc::correlation_id());
        let scope = root.join("project");
        let sibling = root.join("project-other");
        fs::create_dir_all(&scope).unwrap();
        fs::create_dir_all(&sibling).unwrap();
        fs::write(scope.join("中文 & file.txt"), "fixture").unwrap();
        assert!(existing_scoped_path(&scope, &scope.join("中文 & file.txt")).is_ok());
        for path in [
            scope.join("../project-other"),
            sibling.clone(),
            PathBuf::from("relative.txt"),
        ] {
            assert_eq!(existing_scoped_path(&scope, &path), Err(PathError::Denied));
        }
        assert_eq!(
            existing_scoped_path(&scope, &scope.join("missing")),
            Err(PathError::Missing)
        );
        #[cfg(windows)]
        assert_eq!(
            existing_scoped_path(&scope, &scope.join("中文 & file.txt:secret")),
            Err(PathError::Denied)
        );
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    #[cfg(windows)]
    fn junction_to_outside_scope_is_denied() {
        // mklink /J needs no symlink privilege. Paths are generated by the backend.
        let root = std::env::temp_dir().join(super::super::ipc::correlation_id());
        let scope = root.join("project");
        let outside = root.join("outside");
        fs::create_dir_all(&scope).unwrap();
        fs::create_dir_all(&outside).unwrap();
        fs::write(outside.join("secret.txt"), "synthetic").unwrap();
        let junction = scope.join("escape");
        let status = std::process::Command::new("cmd.exe")
            .args(["/d", "/c", "mklink", "/J"])
            .arg(&junction)
            .arg(&outside)
            .output()
            .unwrap();
        assert!(status.status.success(), "fixture junction creation failed");
        assert_eq!(
            existing_scoped_path(&scope, &junction.join("secret.txt")),
            Err(PathError::Denied)
        );
        fs::remove_dir(&junction).unwrap();
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn approvals_cannot_be_forged_replayed_or_used_for_changed_operations() {
        let mut approval = PendingApproval::new(
            "task-a".into(),
            "operation-a".into(),
            OperationKind::Command,
            100,
        );
        for (task, op, window, now) in [
            ("task-b", "operation-a", "main", 1),
            ("task-a", "operation-b", "main", 1),
            ("task-a", "operation-a", "remote", 1),
            ("task-a", "operation-a", "main", 100),
        ] {
            assert!(!approval.decide(task, op, window, now, true));
        }
        assert!(approval.decide("task-a", "operation-a", "main", 1, true));
        assert!(!approval.decide("task-a", "operation-a", "main", 2, true));
        for kind in [OperationKind::Unknown, OperationKind::FileChange] {
            let mut pending = PendingApproval::new("t".into(), "o".into(), kind, 10);
            assert!(!pending.decide("t", "o", "main", 1, false));
            assert!(!pending.decide("t", "o", "main", 2, true));
        }
        let mut unknown = PendingApproval::new("t".into(), "o".into(), OperationKind::Unknown, 10);
        assert!(!unknown.decide("t", "o", "main", 1, true));
    }
}
